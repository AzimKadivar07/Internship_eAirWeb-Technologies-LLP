// 1. == and === operator
// Equality (checks only value)
console.log(5 == "5");   // true

// Strict equality (checks value and type)
console.log(5 === "5");  // false

// 2. inquality operator ( opposite of equlity operator )
// Inequality (checks whether values are different)
console.log(5 != "6");   // true

// Strict inequality (checks value and type)
console.log(5 !== "5");  // true

//  3. Relational operators
// Relational operators
console.log(10 > 5);    // true  (Greater than)
console.log(5 < 10);    // true  (Less than)
console.log(10 >= 10);  // true  (Greater than or equal to)
console.log(5 <= 10);   // true  (Less than or equal to)